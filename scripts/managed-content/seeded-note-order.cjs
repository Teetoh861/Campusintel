// scripts/managed-content/seeded-note-order.cjs — Give the seeded notes the order the seed lists them in.
// Notes follow their position (20261111090000_study_guide_notes.sql); the seed wrote none, so its notes would follow
// their ids. This migration numbers each course's seeded notes in seed order, and only notes the seed still owns
// without a position: an operator's order, once set, is kept.
const assert = require('node:assert/strict')

const NOTE_ORDER_MIGRATION = '20261111110000_seeded_note_order.sql'

/** Each seeded note with its position: 1, 2, … within its course, in the order the seed lists them. */
function seededNoteOrder(manifest) {
  const next = new Map()
  return manifest.items.filter(item => item.kind === 'note').map(item => {
    const position = (next.get(item.courseId) ?? 0) + 1
    next.set(item.courseId, position)
    return { itemId: item.itemId, position }
  })
}

function noteOrderSql(manifest) {
  const rows = seededNoteOrder(manifest)
  assert.ok(rows.length > 0, 'the seed lists notes')
  return [
    `-- supabase/migrations/${NOTE_ORDER_MIGRATION}`,
    '-- GENERATED by scripts/managed-content/generate.cjs from committed repository content. Do not edit by hand.',
    '-- The seeded notes (20261002130000_repository_content_seed.sql) shown in the order the seed lists them: each',
    "-- course's notes are numbered 1, 2, … Only a seeded note without a position is numbered, so a rerun changes",
    '-- nothing and an order set since is kept.',
    '',
    'update public.managed_content_items i set position = o.position',
    '  from (values',
    rows.map(row => `    ('${row.itemId}'::uuid, ${row.position})`).join(',\n'),
    '  ) as o(id, position)',
    `  where i.id = o.id and i.kind = 'note' and i.position is null and i.created_by = '${manifest.actor}';`,
    '',
  ].join('\n')
}

module.exports = { NOTE_ORDER_MIGRATION, noteOrderSql, seededNoteOrder }
