const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { buildManifest } = require('./source-manifest.cjs')
const { CORRECTIONS } = require('./corrections.cjs')
const { absentBankOutputs, bankOutputs, buildImports, publishedCbt } = require('./official-banks.cjs')
const { OVERVIEW_MIGRATION, overviewMigrationSql, overviewRevisions } = require('./overview-revisions.cjs')
const { checkManifest, guideOutputs, guidePlans, guidePublished } = require('./study-guides.cjs')
const { NOTE_ORDER_MIGRATION, noteOrderSql } = require('./seeded-note-order.cjs')

const ROOT = path.resolve(__dirname, '../..')
const SEED_PATH = path.join(ROOT, 'supabase/migrations/20261002130000_repository_content_seed.sql')
const TEST_PATH = path.join(ROOT, 'supabase/tests/repository_content_parity.test.sql')
const MIGRATIONS = path.join(ROOT, 'supabase/migrations')
const FAMILIES = ['course_overview', 'note', 'cbt_question', 'theory_question', 'model_answer', 'rubric']

function sqlLiteral(value) {
  return `'${value.replaceAll("'", "''")}'`
}

function jsonLiteral(value, tag) {
  const serialized = JSON.stringify(value)
  assert.ok(!serialized.includes(`$${tag}$`), `source content contains SQL delimiter ${tag}`)
  return `$${tag}$${serialized}$${tag}$::jsonb`
}

function seedSql(manifest) {
  return `-- supabase/migrations/20261002130000_repository_content_seed.sql
-- GENERATED by scripts/managed-content/generate.cjs from committed repository content.
-- The reserved actor UUID is a migration provenance marker, never an Auth account.
-- Replaying this seed skips unchanged migration-owned records and never rewrites operator edits.

create function private.replay_repository_content_seed()
returns void language plpgsql security invoker set search_path = '' as $repository_migration$
declare
  v_manifest jsonb := ${jsonLiteral(manifest, 'repository_source')};
  v_actor uuid := '${manifest.actor}'::uuid;
  v_course jsonb;
  v_item jsonb;
  v_existing public.managed_content_items%rowtype;
  v_parent uuid;
begin
  for v_course in select value from jsonb_array_elements(v_manifest->'courses') loop
    if not exists (
      select 1 from public.courses
      where id = (v_course->>'courseId')::uuid
        and content_key = v_course->>'contentKey'
    ) then
      raise exception 'Repository course identity mismatch: %', v_course->>'contentKey';
    end if;
  end loop;

  for v_item in select value from jsonb_array_elements(v_manifest->'items') loop
    v_parent := (v_item->>'parentItemId')::uuid;
    perform private.assert_managed_payload(v_item->>'kind', v_item->'payload');
    select * into v_existing from public.managed_content_items
      where id = (v_item->>'itemId')::uuid for update;
    if found then
      if v_existing.created_by is distinct from v_actor or
         v_existing.course_id is distinct from (v_item->>'courseId')::uuid or
         v_existing.kind is distinct from v_item->>'kind' or
         v_existing.question_id is distinct from (v_item->>'questionId')::uuid or
         v_existing.source_key is distinct from v_item->>'sourceKey' or
         v_existing.parent_item_id is distinct from v_parent or
         not exists (
           select 1 from public.managed_content_revisions r
           where r.item_id = v_existing.id and r.revision = 1
             and r.payload = v_item->'payload' and r.authored_by = v_actor
         ) or not exists (
           select 1 from public.managed_content_reviews r
           where r.item_id = v_existing.id and r.revision = 1
             and r.lock_version = 2 and r.decision = 'approved'
             and r.parent_revision is not distinct from
               case when v_parent is null then null else 1 end
             and r.reviewed_by = v_actor
         ) or not exists (
           select 1 from public.managed_content_publications p
           where p.item_id = v_existing.id and p.lock_version = 3
             and p.action = 'publish' and p.revision = 1
             and p.parent_revision is not distinct from
               case when v_parent is null then null else 1 end
             and p.acted_by = v_actor
         ) then
        raise exception 'Existing item is not the same migration-owned record: %',
          v_item->>'itemId';
      end if;
      continue;
    end if;

    insert into public.managed_content_items (
      id, course_id, kind, question_id, source_key, parent_item_id,
      current_revision, approved_revision, published_revision,
      published_parent_revision, lock_version, created_by
    ) values (
      (v_item->>'itemId')::uuid, (v_item->>'courseId')::uuid,
      v_item->>'kind', (v_item->>'questionId')::uuid,
      v_item->>'sourceKey', v_parent, 1, 1, 1,
      case when v_parent is null then null else 1 end, 3, v_actor
    );
    insert into public.managed_content_revisions (item_id, revision, payload, authored_by)
    values ((v_item->>'itemId')::uuid, 1, v_item->'payload', v_actor);
    insert into public.managed_content_reviews (
      item_id, revision, parent_revision, decision, reviewed_by, lock_version
    ) values (
      (v_item->>'itemId')::uuid, 1,
      case when v_parent is null then null else 1 end,
      'approved', v_actor, 2
    );
    insert into public.managed_content_publications (
      item_id, lock_version, action, revision, parent_revision, acted_by
    ) values (
      (v_item->>'itemId')::uuid, 3, 'publish', 1,
      case when v_parent is null then null else 1 end, v_actor
    );
  end loop;
end;
$repository_migration$;

revoke all on function private.replay_repository_content_seed()
  from public, anon, authenticated, service_role;
select private.replay_repository_content_seed();
`
}

function snapshot(item) {
  return {
    itemId: item.itemId, courseId: item.courseId, kind: item.kind,
    questionId: item.questionId, sourceKey: item.sourceKey,
    parentItemId: item.parentItemId, revision: 1, payload: item.payload,
  }
}

/** The parity test compares what is published after every migration: an imported course publishes its bank, a
 *  revised overview publishes its revision two, and an imported study guide publishes its notes, theory items and the
 *  overview revision after that. */
function testSql(manifest, plans, revisions, guides) {
  const imported = new Map(plans.map(plan => [plan.courseId, plan]))
  const revised = new Map(revisions.map(row => [row.itemId, row]))
  const guide = guidePublished(guides)
  const published = item => guide.overviews.has(item.itemId)
    ? { ...snapshot(item), ...guide.overviews.get(item.itemId) }
    : revised.has(item.itemId) ? { ...snapshot(item), revision: 2, payload: revised.get(item.itemId).after } : snapshot(item)
  // Repository courses, then the courses created for their official bank.
  const registry = [...manifest.courses, ...plans.filter(plan => plan.shell)
    .map(plan => ({ contentKey: plan.slug, slug: plan.slug, courseId: plan.courseId, created: plan }))]
  const lines = [
    '-- supabase/tests/repository_content_parity.test.sql — Generated source-to-published parity snapshots.',
    '-- GENERATED by scripts/managed-content/generate.cjs; do not hand-maintain.',
    'begin;',
    'select no_plan();',
    '',
    `select is((select count(*)::int from public.courses), ${registry.length},`,
    "  'every repository course identity is present');",
    `select ok((select jsonb_object_agg(content_key, id::text) from public.courses) = ${jsonLiteral(
      Object.fromEntries(registry.map(row => [row.contentKey, row.courseId])), 'registry_expected')},`,
    "  'repository UUIDs match the committed registry for every course');",
    '',
    'insert into auth.users (instance_id, id, aud, role, email, encrypted_password,',
    '  email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at)',
    "values ('00000000-0000-0000-0000-000000000000',",
    "  '33333333-3333-4333-8333-333333333333', 'authenticated', 'authenticated',",
    "  'repository-parity-student@example.test', 'x', now(),",
    "  '{\"provider\":\"email\",\"providers\":[\"email\"]}', '{}', now(), now());",
    'insert into auth.sessions(id, user_id, created_at, updated_at) values',
    "  ('cccccccc-cccc-4ccc-8ccc-cccccccccccc',",
    "   '33333333-3333-4333-8333-333333333333', now(), now());",
    '-- The parity reader is an operator: it checks all published courses, independently of student scope.',
    "update public.profiles set role = 'operator' where id = '33333333-3333-4333-8333-333333333333';",
    'insert into public.entitlement_grants (user_id, source, starts_at, ends_at, ai_terms, created_by) values',
    "  ('33333333-3333-4333-8333-333333333333', 'manual', now() - interval '1 day', now() + interval '1 day', 'none', 'test');",
    'set local role authenticated;',
    'set local request.jwt.claims =',
    "  '{\"sub\":\"33333333-3333-4333-8333-333333333333\",\"role\":\"authenticated\",\"session_id\":\"cccccccc-cccc-4ccc-8ccc-cccccccccccc\"}';",
    '',
  ]
  for (const course of registry) {
    for (const family of FAMILIES) {
      const bank = family === 'cbt_question' ? imported.get(course.courseId) : undefined
      const expected = (bank ? publishedCbt(bank)
        : [...manifest.items.filter(item => item.courseId === course.courseId && item.kind === family).map(published),
          ...guide.items.filter(item => item.courseId === course.courseId && item.kind === family)])
        .sort((left, right) => left.sourceKey < right.sourceKey ? -1 : left.sourceKey > right.sourceKey ? 1 : 0)
      // CBT questions never reach a student through the content read (20261025100000_server_run_practice.sql): the
      // student read is checked to withhold them, and their published rows are compared as the owner reads them.
      const cbt = family === 'cbt_question'
      if (cbt) {
        lines.push(`select is((select count(*)::int from public.read_published_managed_content('${course.courseId}')`)
        lines.push(`  where kind = '${family}'), 0,`)
        lines.push(`  ${sqlLiteral(`${course.contentKey}: CBT questions are withheld from the student content read`)});`)
        lines.push('reset role;')
      }
      lines.push(`select ok((select coalesce(jsonb_agg(jsonb_build_object(`)
      lines.push("  'itemId', item_id, 'courseId', course_id, 'kind', kind,")
      lines.push("  'questionId', question_id, 'sourceKey', source_key,")
      lines.push("  'parentItemId', parent_item_id, 'revision', revision,")
      lines.push("  'payload', payload) order by source_key collate \"C\"), '[]'::jsonb)")
      if (cbt) {
        lines.push('  from (select i.id item_id, i.course_id, i.kind, i.question_id, i.source_key, i.parent_item_id,')
        lines.push('    i.published_revision revision, r.payload from public.managed_content_items i')
        lines.push('    join public.managed_content_revisions r on r.item_id = i.id and r.revision = i.published_revision')
        lines.push(`    where i.course_id = '${course.courseId}' and i.published_revision is not null) published`)
      } else {
        lines.push(`  from public.read_published_managed_content('${course.courseId}')`)
      }
      lines.push(`  where kind = '${family}') = ${jsonLiteral(expected, 'expected_content')},`)
      lines.push(`  ${sqlLiteral(`${course.contentKey}: ${family} published payload and identity match source`)});`)
      if (cbt) lines.push('set local role authenticated;')
    }
  }
  lines.push('', 'reset role;')
  lines.push(`select is((select count(*)::int from public.managed_content_items where created_by = '${manifest.actor}'),`)
  lines.push(`  ${manifest.items.length}, 'all source items carry migration provenance');`)
  lines.push(`select is((select count(*)::int from public.managed_content_items where created_by = '${manifest.actor}'`)
  lines.push('  and (current_revision <> 1 or approved_revision <> 1 or published_revision <> 1)')
  lines.push(`  and not (kind = 'course_overview' and id = any (array[${revisions.map(row => `'${row.itemId}'`).join(', ')}]::uuid[]))`)
  if (plans.length) {
    lines.push(`  and not (kind = 'cbt_question' and course_id = any (array[${plans.map(plan => `'${plan.courseId}'`).join(', ')}]::uuid[]))),`)
    lines.push("  0, 'all live repository items outside the imported banks and revised overviews are approved and published at revision one');")
  } else {
    lines[lines.length - 1] += '),'
    lines.push("  0, 'all live repository items outside the revised overviews are approved and published at revision one');")
  }
  lines.push(`select is((select count(*)::int from public.managed_content_reviews where reviewed_by = '${manifest.actor}'`)
  lines.push("  and decision = 'rejected'), 0, 'migration never publishes a rejected revision');")
  lines.push(`select is((select count(*)::int from public.managed_content_items i`)
  lines.push('  join public.managed_content_items parent on parent.id = i.parent_item_id')
  lines.push(`  where i.created_by = '${manifest.actor}' and i.kind = 'model_answer'`)
  lines.push('    and i.published_parent_revision is distinct from parent.published_revision),')
  lines.push("  0, 'every published model answer binds the published theory revision');")
  lines.push(`select is((select count(*)::int from public.managed_content_items where created_by = '${manifest.actor}'`)
  lines.push("  and kind = 'rubric'), 0, 'no source rubric was fabricated');")
  lines.push('select * from finish();', 'rollback;', '')
  return lines.join('\n')
}

/** The one source item a correction names; its current source text must already be the corrected text. */
function correctedItem(manifest, correction) {
  const matches = manifest.items.filter(item => item.courseId === correction.courseId && item.kind === correction.kind
    && item.sourceKey === correction.sourceKey)
  assert.equal(matches.length, 1, `correction target ${correction.sourceKey}`)
  assert.equal(matches[0].payload[correction.field], correction.corrected,
    `${correction.sourceKey}.${correction.field} in source must hold the corrected text`)
  return matches[0]
}

/** The manifest as the seed migration committed it: every later correction undone. */
function seededManifest(manifest) {
  const items = manifest.items.map(item => ({ ...item, payload: { ...item.payload } }))
  const seeded = { ...manifest, items }
  for (const correction of CORRECTIONS) correctedItem(seeded, correction).payload[correction.field] = correction.seeded
  return seeded
}

/** One correction migration. Live migration-owned rows that still hold the seeded text are corrected; operator edits
 *  are left alone. The committed seed replay compares revision one with the text it seeded, so the replay is wrapped:
 *  it undoes these corrections, runs the earlier replay unchanged, and reapplies them to the rows it undid and to any
 *  target the replay created because it was missing. */
function correctionSql(manifest, migration) {
  const corrections = CORRECTIONS.filter(correction => correction.migration === migration)
  const version = migration.split('_')[0]
  const field = correction => sqlLiteral(correction.field)
  const set = (correction, text) =>
    `set payload = jsonb_set(r.payload, ${sqlLiteral(`{${correction.field}}`)}, to_jsonb(${sqlLiteral(text)}::text))`
  const lines = [
    `-- supabase/migrations/${migration}`,
    '-- GENERATED by scripts/managed-content/generate.cjs from scripts/managed-content/corrections.cjs.',
    '-- Approved content correction after the repository seed. Revision numbers, reviews and publications are unchanged.',
  ]
  const owned = item => [`  where r.item_id = '${item.itemId}'::uuid and r.revision = 1 and r.authored_by = '${manifest.actor}'::uuid`]
  for (const correction of corrections) {
    const item = correctedItem(manifest, correction)
    lines.push('update public.managed_content_revisions r', `  ${set(correction, correction.corrected)}`, ...owned(item),
      `    and r.payload ->> ${field(correction)} = ${sqlLiteral(correction.seeded)}`,
      `    and exists (select 1 from public.managed_content_items i where i.id = r.item_id and i.created_by = '${manifest.actor}'::uuid`,
      '      and i.current_revision = 1 and i.published_revision = 1);')
  }
  const previous = `replay_repository_content_seed_before_${version}`
  lines.push('', `alter function private.replay_repository_content_seed() rename to ${previous};`,
    'create function private.replay_repository_content_seed()',
    "returns void language plpgsql security invoker set search_path = '' as $replay$",
    'declare', '  v_undone uuid[] := array[]::uuid[];', '  v_present uuid[];', '  v_item uuid;', 'begin',
    '  -- Targets that exist before the replay; any other target the replay creates is new and gets the correction too.',
    '  select coalesce(array_agg(i.id), array[]::uuid[]) into v_present from public.managed_content_items i',
    `    where i.id = any (array[${corrections.map(correction => `'${correctedItem(manifest, correction).itemId}'`).join(', ')}]::uuid[]);`)
  for (const correction of corrections) {
    const item = correctedItem(manifest, correction)
    lines.push('  v_item := null;', '  update public.managed_content_revisions r', `    ${set(correction, correction.seeded)}`,
      ...owned(item).map(line => '  ' + line), `      and r.payload ->> ${field(correction)} = ${sqlLiteral(correction.corrected)}`,
      '    returning r.item_id into v_item;', '  if v_item is not null then v_undone := v_undone || v_item; end if;')
  }
  lines.push(`  perform private.${previous}();`)
  for (const correction of corrections) {
    const item = correctedItem(manifest, correction)
    lines.push('  update public.managed_content_revisions r', `    ${set(correction, correction.corrected)}`,
      ...owned(item).map(line => '  ' + line),
      `      and r.payload ->> ${field(correction)} = ${sqlLiteral(correction.seeded)}`,
      // Rows undone above, or a target the replay just created as a live, migration-owned revision one.
      '      and (r.item_id = any (v_undone) or (r.item_id <> all (v_present) and exists (select 1',
      `        from public.managed_content_items i where i.id = r.item_id and i.created_by = '${manifest.actor}'::uuid`,
      '          and i.current_revision = 1 and i.published_revision = 1)));')
  }
  lines.push('end;', '$replay$;', '',
    `revoke all on function private.replay_repository_content_seed(), private.${previous}()`,
    '  from public, anon, authenticated, service_role;')
  return lines.join('\n') + '\n'
}

/** Each bank's topics by course code, for the guides' practice buttons. */
const buildBanks = plans => new Map(plans.map(plan => [plan.code, plan.bank]))

const manifest = buildManifest()
const { plans } = buildImports(manifest)
const revisions = overviewRevisions(manifest)
checkManifest()
const guides = guidePlans(manifest, buildBanks(plans), revisions)
const outputs = [[SEED_PATH, seedSql(seededManifest(manifest))], [TEST_PATH, testSql(manifest, plans, revisions, guides)],
  ...[...new Set(CORRECTIONS.map(correction => correction.migration))]
    .map(migration => [path.join(MIGRATIONS, migration), correctionSql(manifest, migration)]),
  ...bankOutputs(manifest, plans),
  [path.join(MIGRATIONS, OVERVIEW_MIGRATION), overviewMigrationSql(manifest.actor, revisions)],
  ...guideOutputs(guides),
  [path.join(MIGRATIONS, NOTE_ORDER_MIGRATION), noteOrderSql(manifest)]]
if (process.argv[2] === '--check') {
  for (const [filename, generated] of outputs) {
    assert.ok(fs.existsSync(filename), `${path.relative(ROOT, filename)} is missing; regenerate from source`)
    assert.equal(fs.readFileSync(filename, 'utf8'), generated,
      `${path.relative(ROOT, filename)} is stale; regenerate from source`)
  }
  for (const filename of absentBankOutputs(plans)) {
    assert.ok(!fs.existsSync(filename), `${path.relative(ROOT, filename)} must not exist; regenerate from source`)
  }
  process.stdout.write(`Source-derived artifacts match ${manifest.items.length} items across ${manifest.courses.length} courses`
    + `, ${plans.length} official bank imports and ${guides.length} study guides.\n`)
} else if (process.argv.length === 2) {
  for (const [filename, generated] of outputs) fs.writeFileSync(filename, generated)
  for (const filename of absentBankOutputs(plans)) fs.rmSync(filename, { force: true })
  process.stdout.write(`Generated ${manifest.items.length} items across ${manifest.courses.length} courses`
    + `, ${plans.length} official bank imports and ${guides.length} study guides.\n`)
} else {
  process.stderr.write('Usage: node scripts/managed-content/generate.cjs [--check]\n')
  process.exitCode = 2
}
