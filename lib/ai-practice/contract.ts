// lib/ai-practice/contract.ts — Provider-neutral contract for personal, unverified AI practice questions.
// Nothing here knows which AI provider produced a set; saved sets must stay readable after a provider change.
import { z } from 'zod'
import type { ProviderDiagnostic, ProviderErrorCode } from './provider'

/** Every bound the generator enforces. Changing one is a product decision, not a refactor. */
export const AI_PRACTICE_LIMITS = {
  /** Below this many words the material cannot support honest questions. */
  minSourceWords: 150,
  /** About 15K tokens of English; keeps one request's input cost bounded. */
  maxSourceChars: 60_000,
  /** Hard ceiling on what the request parser will even read. */
  maxRequestTextChars: 400_000,
  maxPassageChars: 1_200,
  maxPassages: 120,
  minQuestions: 1,
  /** Product rule: one student request asks for exactly this many questions. */
  questionsPerRequest: 5,
  maxQuestions: 5,
  optionCount: 4,
  maxPromptChars: 600,
  maxOptionChars: 240,
  maxExplanationChars: 1_200,
  maxSectionChars: 120,
  minQuoteChars: 12,
  maxQuoteChars: 400,
  /**
   * Ceiling on generated tokens, thinking included. Five questions of JSON are about 1,200 tokens;
   * the rest is headroom for adaptive thinking at medium effort. A reply that hits the cap fails
   * as truncated-output and costs the student no allowance.
   */
  maxOutputTokens: 8_000,
} as const

/** Bumped whenever the prompt or output schema changes, so stored sets stay attributable. */
export const AI_PRACTICE_PROMPT_VERSION = 'upload-practice-v1'

/** Shown wherever personal sets appear (PRD 4.3). The UI slice must render it verbatim. */
export const PERSONAL_PRACTICE_DISCLAIMER =
  'These questions were generated by AI from material you uploaded. They are for personal study only ' +
  'and have not been checked or verified by CampusIntell.'

const boundedText = (limit: number) => z.string().max(limit).refine(value => value.trim().length > 0)

export const generationRequestSchema = z.object({
  course: z.object({
    courseId: boundedText(120),
    code: boundedText(24),
    title: boundedText(200),
  }).strict(),
  source: z.object({
    // Private upload identity from the future storage slice; the generator never reads storage itself.
    documentId: z.string().uuid(),
    fileName: boundedText(255),
    extractedText: z.string().max(AI_PRACTICE_LIMITS.maxRequestTextChars),
  }).strict(),
  questionCount: z.number().int().min(AI_PRACTICE_LIMITS.minQuestions).max(AI_PRACTICE_LIMITS.maxQuestions),
}).strict()
export type GenerationRequest = z.infer<typeof generationRequestSchema>

/** Where a question's correct answer is supported in the student's own document. */
export type SourceGrounding = {
  documentId: string
  sourceSha256: string
  passageId: string
  passageStart: number
  passageEnd: number
  /** Verbatim excerpt of the passage that supports the keyed answer. */
  quote: string
}

/**
 * One personal question. The answer fields deliberately match the operator `cbt_question`
 * payload, so a later operator promotion (PRD 4.7) can reuse the editor contract unchanged.
 */
export type PersonalPracticeQuestion = {
  id: string
  prompt: string
  options: string[]
  correctOption: number
  explanation: string
  section: string
  grounding: SourceGrounding
}

export type GenerationConfidence = 'medium' | 'high'

/** The saved format. `origin`, `visibility` and `verification` are fixed literals, never inputs. */
export type PersonalPracticeSet = {
  formatVersion: 1
  origin: 'ai-generated'
  visibility: 'personal'
  verification: 'unverified'
  course: GenerationRequest['course']
  source: { documentId: string; fileName: string; sha256: string; charCount: number; passageCount: number }
  questions: PersonalPracticeQuestion[]
  generation: {
    provider: string
    model: string
    promptVersion: string
    generatedAt: string
    confidence: GenerationConfidence
    requestedQuestionCount: number
    rejectedQuestionCount: number
  }
}

export type UsageReport = {
  provider: string
  model: string
  inputTokens: number
  outputTokens: number
  cacheReadInputTokens: number
  cacheCreationInputTokens: number
  /** Null when the serving model has no known price; never guessed. */
  estimatedCostUsd: number | null
  durationMs: number
}

export type InsufficientReason = 'empty' | 'too-short' | 'too-large' | 'low-confidence'
export type FlagReason = 'unrelated-to-course' | 'inappropriate' | 'provider-refusal'
export type FailureReason =
  | 'invalid-request' | 'not-configured' | 'timeout' | 'rate-limited'
  | 'provider-unavailable' | 'invalid-output' | 'truncated-output'

/** Every outcome is safe to show a student; none carries source text, prompts or credentials. */
export type GenerationOutcome =
  | { status: 'generated'; set: PersonalPracticeSet; usage: UsageReport }
  | { status: 'insufficient-source'; reason: InsufficientReason; usage: UsageReport | null }
  | { status: 'flagged-for-review'; reason: FlagReason; usage: UsageReport | null }
  | { status: 'failed'; reason: FailureReason; usage: UsageReport | null
      /** Operator diagnostics only: log them server-side, never return them to the student. */
      providerError?: ProviderErrorCode; providerDiagnostic?: ProviderDiagnostic }
